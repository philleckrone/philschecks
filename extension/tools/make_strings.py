# -*- coding: utf-8 -*-
# Writes src/shared/strings.js (PC.strings = {en, es, fr}) from Project Checker's resource files,
# Project_Checker/ProjectChecker/Resources/Strings.{en,es,fr}.xaml: the report strings the ported
# checks use (Rpt_*, Check_<id>_*, Opt_<id>_*, Cat_<id>_*, Msg_<id>_*, Rpt_<id>_*).
#     python tools/make_strings.py
# Add a check's id to CHECK_IDS when it is ported. OVERRIDES corrects strings for the extension only.
import json, os, re
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
REPO = os.path.dirname(os.path.dirname(ROOT))
RES = os.path.join(REPO, 'Project_Checker', 'ProjectChecker', 'Resources')
OUT = os.path.join(ROOT, 'src', 'shared', 'strings.js')
LANGS = ['en', 'es', 'fr']

CHECK_IDS = ['shortv1', 'titles', 'nested', 'refnomark', 'qerrors', 'footnotes']
GENERIC = ['Rpt_OptionsUsed', 'Rpt_Option', 'Rpt_Value', 'Rpt_NoFindings', 'Rpt_Reference', 'Rpt_Text',
           'Rpt_Message', 'Rpt_Book', 'Rpt_Failed', 'Rpt_Empty']

OVERRIDES = {
    # The Spanish tip still described the old default (No).
    'es': {'Opt_titles_DisplayHeader_Tip': u'Sí (predeterminado) agrega una columna al informe que muestra el texto \\h (encabezado de página) de cada libro, o "ausente" si no está presente. No muestra solo el título \\mt. Se activa automáticamente si Ordenar por encabezado está en Sí.'},
}

# Strings Project Checker doesn't have (its message stays English); the English one is the original's.
EXTRA = {
    'en': {'Msg_shortv1_Chars': u'{0} chars (set = {1})'},
    'es': {'Msg_shortv1_Chars': u'{0} caracteres (mínimo = {1})'},
    'fr': {'Msg_shortv1_Chars': u'{0} caractères (minimum = {1})'},
}

MENU = {'en': u'Phils Custom (cms) Checks...',
        'es': u'Verificaciones personalizadas (cms) de Phil...',
        'fr': u'Vérifications personnalisées (cms) de Phil...'}
# The Checks panel lists every extension's checks together; this says where ours come from.
PANEL_SUFFIX = u' (Phil)'

X = '{http://schemas.microsoft.com/winfx/2006/xaml}Key'

with open(os.path.join(REPO, 'Marker_Spaces', 'extension', 'contributions', 'localizedStrings.json'), encoding='utf-8') as _f:
    MS_STRINGS = json.load(_f)['localizedStrings']


def read(lang):
    root = ET.parse(os.path.join(RES, 'Strings.%s.xaml' % lang)).getroot()
    out = {}
    for el in root:
        key = el.get(X)
        if key is not None:
            out[key] = el.text or ''
    return out


def wanted(key):
    if key in GENERIC:
        return True
    for cid in CHECK_IDS:
        if re.match(r'^(Check|Opt|Cat|Msg|Rpt)_%s_' % re.escape(cid), key):
            return True
    return False


def main():
    tables = {}
    for lang in LANGS:
        all_ = read(lang)
        t = dict((k, v) for k, v in all_.items() if wanted(k))
        t.update(EXTRA.get(lang, {}))
        t.update(OVERRIDES.get(lang, {}))
        tables[lang] = dict(sorted(t.items()))
    missing = [k for k in tables['en'] if any(k not in tables[l] for l in LANGS)]
    lines = ['// Generated by tools/make_strings.py from Project Checker\'s Strings.*.xaml - do not edit.',
             'PC.strings = ' + json.dumps(tables, ensure_ascii=True, indent=1) + ';', '']
    with open(OUT, 'w', encoding='ascii', newline='\n') as f:
        f.write('\n'.join(lines))
    print('wrote %s (%d keys)' % (OUT, len(tables['en'])))

    # contributions/localizedStrings.json: the menu item, the Checks panel's names and the message.
    loc = {}
    for lang in LANGS:
        t = tables[lang]
        d = {'%philsChecks_menu_open%': MENU[lang], '%philsChecks_message%': '{message}'}
        for cid in CHECK_IDS:
            d['%%philsChecks_check_%s_name%%' % cid] = t['Check_%s_Name' % cid] + PANEL_SUFFIX
            d['%%philsChecks_check_%s_description%%' % cid] = t['Check_%s_Desc' % cid]
        # Marker Spaces is built in (tools/build.py): its check's strings, without its menu item.
        for k, v in MS_STRINGS.get(lang, {}).items():
            if k == '%markerSpaces_menu_open%':
                continue
            d[k] = v + PANEL_SUFFIX if k == '%markerSpaces_checkName%' else v
        loc[lang] = d
    path = os.path.join(ROOT, 'contributions', 'localizedStrings.json')
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        json.dump({'metadata': {}, 'localizedStrings': loc}, f, ensure_ascii=False, indent=2)
        f.write('\n')
    print('wrote %s' % path)
    for k in missing:
        print('  not in every language (English is used):', k)


if __name__ == '__main__':
    main()
